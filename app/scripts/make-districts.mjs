// Builds migrations/0005_districts.sql from data/postcode-districts.csv (see data/README.md).
import { readFileSync, writeFileSync } from 'node:fs';

const rows = readFileSync(new URL('../data/postcode-districts.csv', import.meta.url), 'utf8').trim().split(/\r?\n/).slice(1);
const q = (s) => (s ? `'${s.replace(/'/g, "''")}'` : 'NULL');
const values = [];
for (const line of rows) {
  const [outcode, , , lat, lng, town, region] = line.split(',');
  if (!/^[A-Z]{1,2}[0-9][A-Z0-9]?$/.test(outcode) || !lat || !lng) continue;
  values.push(`(${q(outcode)},${Number(lat).toFixed(5)},${Number(lng).toFixed(5)},${q(town || region)})`);
}
let sql = `-- Step 5: postcode district centres for distance search (generated by scripts/make-districts.mjs).
CREATE TABLE postcode_districts (
  outcode TEXT PRIMARY KEY,  -- e.g. TF1
  lat REAL NOT NULL,
  lng REAL NOT NULL,
  town TEXT                  -- nearby town, for display ("near Wellington")
);
ALTER TABLE producers ADD COLUMN district TEXT;  -- outcode of the business postcode
UPDATE producers SET district = substr(postcode, 1, instr(postcode, ' ') - 1) WHERE postcode LIKE '% %';
CREATE INDEX producers_district ON producers(district);
`;
for (let i = 0; i < values.length; i += 250) sql += `INSERT INTO postcode_districts (outcode, lat, lng, town) VALUES\n${values.slice(i, i + 250).join(',\n')};\n`;
writeFileSync(new URL('../migrations/0005_districts.sql', import.meta.url), sql);
console.log(`${values.length} districts`);
